/**
 * Scans src/templates/{category}/{nn}/meta.ts and (re)generates src/templates/metas.ts
 * with static meta imports + dynamic component loaders. Run: npm run gen:templates
 */
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src", "templates");
const skip = new Set(["shared", "ui", "fields.ts", "types.ts", "theme.ts", "registry.ts", "metas.ts"]);

const entries = [];
for (const cat of readdirSync(root)) {
  if (skip.has(cat)) continue;
  const catDir = join(root, cat);
  if (!statSync(catDir).isDirectory()) continue;
  for (const nn of readdirSync(catDir).sort()) {
    const dir = join(catDir, nn);
    if (!statSync(dir).isDirectory()) continue;
    if (!existsSync(join(dir, "meta.ts")) || !existsSync(join(dir, "index.tsx"))) continue;
    entries.push({ cat, nn, ident: `${cat}_${nn}` });
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.",
  'import type { TemplateComponents, TemplateMeta } from "@/templates/types";',
  "",
  ...entries.map((e) => `import { meta as ${e.ident} } from "@/templates/${e.cat}/${e.nn}/meta";`),
  "",
  "export const TEMPLATE_METAS: TemplateMeta[] = [",
  ...entries.map((e) => `  ${e.ident},`),
  "];",
  "",
  "export const TEMPLATE_LOADERS: Record<string, () => Promise<{ components: TemplateComponents }>> = {",
  ...entries.map((e) => `  "${e.cat}-${e.nn}": () => import("@/templates/${e.cat}/${e.nn}"),`),
  "};",
  "",
];

writeFileSync(join(root, "metas.ts"), lines.join("\n"));
console.log(`Registry generated with ${entries.length} templates.`);
