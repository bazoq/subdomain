/**
 * Scans src/templates/{category}/{nn}/meta.ts and (re)generates src/templates/metas.ts
 * with static meta imports + dynamic component loaders. Run: npm run gen:templates
 *
 * The output is deterministic (sorted by category, then folder name) so the committed
 * `metas.ts` never churns between machines. `collectTemplates` / `renderRegistry` are exported
 * for tests; the file is only written when the script is executed directly.
 */
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Non-template entries that live directly under src/templates. */
export const SKIP = new Set(["shared", "ui", "catalog", "fields.ts", "types.ts", "theme.ts", "registry.ts", "metas.ts"]);

/** @param {string} root absolute path to src/templates */
export function collectTemplates(root) {
  const entries = [];
  for (const cat of readdirSync(root).sort()) {
    if (SKIP.has(cat)) continue;
    const catDir = join(root, cat);
    if (!statSync(catDir).isDirectory()) continue;
    for (const nn of readdirSync(catDir).sort()) {
      const dir = join(catDir, nn);
      if (!statSync(dir).isDirectory()) continue;
      if (!existsSync(join(dir, "meta.ts")) || !existsSync(join(dir, "index.tsx"))) continue;
      entries.push({ cat, nn, id: `${cat}-${nn}`, ident: `${cat}_${nn}` });
    }
  }
  return entries;
}

/** @param {{cat: string, nn: string, ident: string}[]} entries */
export function renderRegistry(entries) {
  const lines = [
    "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.",
    'import type { TemplateComponents, TemplateMeta } from "@/templates/types";',
    "",
    ...entries.map((e) => `import { meta as ${e.ident} } from "@/templates/${e.cat}/${e.nn}/meta";`),
    "",
    "export const TEMPLATE_METAS: TemplateMeta[] = [",
    ...entries.map((e) => `  ${e.ident},`),
    "];",
    "",
    "export const TEMPLATE_LOADERS: Record<string, () => Promise<{ components: TemplateComponents }>> = {",
    ...entries.map((e) => `  "${e.cat}-${e.nn}": () => import("@/templates/${e.cat}/${e.nn}"),`),
    "};",
    "",
  ];
  return lines.join("\n");
}

/** @param {string} [cwd] project root (defaults to process.cwd()) */
export function generate(cwd = process.cwd()) {
  const root = join(cwd, "src", "templates");
  const entries = collectTemplates(root);
  return { entries, source: renderRegistry(entries), outFile: join(root, "metas.ts") };
}

const isMain = Boolean(process.argv[1]) && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
  const { entries, source, outFile } = generate();
  writeFileSync(outFile, source);
  console.log(`Registry generated with ${entries.length} templates.`);
}
