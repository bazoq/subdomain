#!/usr/bin/env node
/**
 * Captures real screenshots of every template's live demo (`demo-<templateId>.<root>`) for the marketing
 * site's gallery cards and detail pages, and writes:
 *   public/templates/<id>-desktop.webp   1440px-wide viewport, top ~3600px, resized to 800px wide
 *   public/templates/<id>-mobile.webp    390px-wide viewport (2x), top ~2400px, resized to 390px wide
 *   src/templates/shots.ts                generated manifest (sizes + cache-busting version)
 *
 * Uses the locally installed Chrome (or Edge) through playwright-core, so no browser download is needed.
 * Templates whose demo is missing ("site is not set up") are skipped and keep their CSS fallback.
 *
 *   npm run shots                                   all templates from https://demo-<id>.baxoq.com
 *   npm run shots -- --only pizza-01,law-02         a subset
 *   npm run shots -- --root localhost:3000          local dev server (http)
 *   npm run shots -- --resolve 216.198.79.65        bypass local DNS (maps *.<root> to that IP)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import sharp from "sharp";
import { chromium } from "playwright-core";
import { collectTemplates } from "./gen-registry.mjs";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

const root = (flag("root") ?? process.env.ROOT_DOMAIN ?? "baxoq.com").replace(/^https?:\/\//, "").replace(/\/+$/, "");
const isLocal = /(^|\.)localhost(:\d+)?$/.test(root);
const only = flag("only")?.split(",").map((s) => s.trim()).filter(Boolean);
const resolveIp = flag("resolve");
const concurrency = Math.max(1, Math.min(6, Number(flag("concurrency") ?? 3)));

const cwd = process.cwd();
const outDir = join(cwd, "public", "templates");
const manifestFile = join(cwd, "src", "templates", "shots.ts");
mkdirSync(outDir, { recursive: true });

const DESKTOP = { width: 1440, height: 900, maxHeight: 3600, outWidth: 800 };
const MOBILE = { width: 390, height: 844, maxHeight: 2400, outWidth: 390 };

function demoUrl(id) {
  return `${isLocal ? "http" : "https"}://demo-${id}.${root}/`;
}

function readManifest() {
  if (!existsSync(manifestFile)) return {};
  const m = /export const TEMPLATE_SHOTS[^=]*=\s*(\{[\s\S]*\});/.exec(readFileSync(manifestFile, "utf8"));
  try {
    return m ? JSON.parse(m[1]) : {};
  } catch {
    return {};
  }
}

function writeManifest(shots) {
  const sorted = Object.fromEntries(Object.entries(shots).sort(([a], [b]) => a.localeCompare(b)));
  const src = [
    "// AUTO-GENERATED by scripts/capture-template-shots.mjs (`npm run shots`) — do not edit by hand.",
    "// Real screenshots of each template's live demo, served from /public/templates/<id>-<device>.webp.",
    "",
    "export interface TemplateShot {",
    "  /** intrinsic size of the stored image */",
    "  width: number;",
    "  height: number;",
    "}",
    "",
    "export const TEMPLATE_SHOTS: Record<string, { v: string; desktop?: TemplateShot; mobile?: TemplateShot }> = " + JSON.stringify(sorted, null, 2) + ";",
    "",
  ].join("\n");
  writeFileSync(manifestFile, src);
}

/** Scroll the whole page so lazy images and reveal-on-scroll sections render, then return to the top. */
async function settle(page) {
  await page.evaluate(async () => {
    const step = Math.max(400, Math.floor(window.innerHeight * 0.8));
    for (let y = 0; y < document.body.scrollHeight; y += step) {
      window.scrollTo(0, y);
      await new Promise((r) => setTimeout(r, 120));
    }
    window.scrollTo(0, 0);
    await new Promise((r) => setTimeout(r, 400));
  });
  await page.evaluate(() => document.fonts?.ready).catch(() => undefined);
  await page.waitForTimeout(500);
}

async function shoot(browser, id, device) {
  const ctx = await browser.newContext({
    viewport: { width: device.width, height: device.height },
    deviceScaleFactor: device === MOBILE ? 2 : 1,
    isMobile: device === MOBILE,
    hasTouch: device === MOBILE,
    reducedMotion: "reduce",
    locale: "en-PK",
    ignoreHTTPSErrors: isLocal,
  });
  const page = await ctx.newPage();
  try {
    const res = await page.goto(demoUrl(id), { waitUntil: "networkidle", timeout: 60_000 });
    const title = await page.title();
    if (!res || res.status() >= 400 || /not set up/i.test(title)) return null;
    await settle(page);
    const fullHeight = await page.evaluate(() => document.documentElement.scrollHeight);
    const clipHeight = Math.min(fullHeight, device.maxHeight);
    const png = await page.screenshot({ type: "png", clip: { x: 0, y: 0, width: device.width, height: clipHeight }, fullPage: true });
    const img = sharp(png).resize({ width: device.outWidth }).webp({ quality: 72, effort: 5 });
    const buf = await img.toBuffer();
    const meta = await sharp(buf).metadata();
    writeFileSync(join(outDir, `${id}-${device === MOBILE ? "mobile" : "desktop"}.webp`), buf);
    return { width: meta.width, height: meta.height, hash: createHash("sha1").update(buf).digest("hex").slice(0, 8) };
  } finally {
    await ctx.close();
  }
}

async function launch() {
  const launchArgs = resolveIp ? [`--host-resolver-rules=MAP *.${root.split(":")[0]} ${resolveIp}`] : [];
  for (const channel of ["chrome", "msedge"]) {
    try {
      return await chromium.launch({ channel, args: launchArgs });
    } catch {
      /* try the next installed browser */
    }
  }
  throw new Error("No local Chrome or Edge found for playwright-core. Install Google Chrome and retry.");
}

async function main() {
  const all = collectTemplates(join(cwd, "src", "templates")).map((e) => e.id);
  const ids = only ? all.filter((id) => only.includes(id)) : all;
  if (!ids.length) throw new Error(`No templates match --only ${only?.join(",")}`);
  console.log(`Capturing ${ids.length} template(s) from ${demoUrl("<id>")} …`);

  const shots = readManifest();
  const browser = await launch();
  const failed = [];
  const skipped = [];
  let done = 0;
  const queue = [...ids];

  async function worker() {
    for (let id = queue.shift(); id; id = queue.shift()) {
      try {
        const desktop = await shoot(browser, id, DESKTOP);
        if (!desktop) {
          skipped.push(id);
          continue;
        }
        const mobile = await shoot(browser, id, MOBILE);
        shots[id] = {
          v: `${desktop.hash}${mobile?.hash ?? ""}`.slice(0, 10),
          desktop: { width: desktop.width, height: desktop.height },
          ...(mobile ? { mobile: { width: mobile.width, height: mobile.height } } : {}),
        };
        done++;
        console.log(`  ✔ ${id}  (${done}/${ids.length})`);
      } catch (err) {
        failed.push(id);
        console.warn(`  ✖ ${id}: ${err instanceof Error ? err.message.split("\n")[0] : err}`);
      }
    }
  }

  try {
    await Promise.all(Array.from({ length: concurrency }, worker));
  } finally {
    await browser.close();
    writeManifest(shots);
  }
  console.log(`Done: ${done} captured, ${skipped.length} skipped (no demo), ${failed.length} failed.`);
  if (skipped.length) console.log(`  skipped: ${skipped.join(", ")}`);
  if (failed.length) {
    console.log(`  failed: ${failed.join(", ")}  (re-run with --only ${failed.join(",")})`);
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
